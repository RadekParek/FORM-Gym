/** Returns a translator with safe English fallback and simple named interpolation. */
export function useT(language: Language) {
  return (key: string, vars: Record<string, string | number> = {}) => {
    if (key === 'exerciseCount' && Number(vars.count) === 1) {
      const word = messages[language]?.exercise ?? messages.en.exercise;
      return `1 ${language === 'de' ? word : word.toLocaleLowerCase(language)}`;
    }
    const template = messages[language]?.[key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
  };
}

