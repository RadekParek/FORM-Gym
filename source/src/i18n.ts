const suggestionKeys = [
  'suggestionProfile',
  'suggestionHirschsprung',
  'suggestionHealth',
  'suggestionYouth',
  'suggestionOlder',
  'suggestionGoal',
  'suggestionStart',
  'suggestionFrequency',
  'suggestionNovice',
  'suggestionExperienced',
];
const suggestionLookup = new Map(suggestionKeys.map((key) => [extraEn[key], key]));

export function suggestionText(language: Language, message: string): string {
  const t = useT(language);
  const key = suggestionLookup.get(message);
  if (key) return t(key);
  const weekly = message.match(/^(\d+) of (\d+) planned training days completed this week\./);
  return weekly ? t('suggestionWeek', { done: weekly[1], goal: weekly[2] }) : message;
}

/** Translate generated starter content once, while preserving all user-written plans. */
export function localizeStarterPlans(
  plans: Record<string, DayPlan>,
  language: Language,
): Record<string, DayPlan> {
  const t = useT(language);
  return Object.fromEntries(
    Object.entries(plans).map(([day, plan]) => {
      const fullBody = plan.title.match(/^Full body ([ABC])$/);
      return [
        day,
        {
          ...plan,
          title: fullBody
            ? t('fullBody', { letter: fullBody[1] })
            : plan.title === 'Rest & reset'
              ? t('restReset')
              : plan.title,
          note:
            plan.note === extraEn.starterGentleNote
              ? t('starterGentleNote')
              : plan.note === extraEn.starterNote
                ? t('starterNote')
                : plan.note,
        },
      ];
    }),
  );
}
