export function featureT(
  language: Language,
  key: Key,
  values: Record<string, string | number> = {},
): string {
  let result =
    common[language]?.[key] ||
    (extra as Partial<Record<Language, Partial<Record<Key, string>>>>)[language]?.[key] ||
    en[key];
  for (const [name, value] of Object.entries(values))
    result = result.replaceAll(`{${name}}`, String(value));
  return result;
}
